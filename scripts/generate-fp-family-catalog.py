"""Regenerate family membership for the existing TodoFP reference catalog.

Only matches catalog names; never invents family membership for unknown titles.
Run from the repository root. Sources are the official Grados D indexes.
"""
import html
import json
import pathlib
import re
import unicodedata
import urllib.request


def normalize(value):
    return "".join(c for c in unicodedata.normalize("NFD", value.lower()) if c.isalnum())


root = pathlib.Path(__file__).resolve().parent.parent
families = {}
for grade in ["grado-medio", "grado-superior", "fp-grado-basico"]:
    url = f"https://todofp.es/que-estudiar/grados-d/{grade}.html"
    with urllib.request.urlopen(url, timeout=30) as response:
        document = response.read().decode("utf-8")
    family = None
    for row in re.findall(r"<tr\b.*?</tr>", document, re.S):
        logo = re.search(r'alt="Logotipo ([^"]+)"', row)
        if logo:
            family = html.unescape(logo.group(1))
        cell = re.search(r'<td[^>]*headers="titulacion[^>]*>(.*?)</td>', row, re.S)
        if cell and family:
            name = html.unescape(re.sub("<[^>]+>", "", cell.group(1))).strip()
            families.setdefault(normalize(name), set()).add(family)

catalog = json.loads((root / "scripts/src/data/cycles.json").read_text())
missing = [cycle["name"] for cycle in catalog if normalize(cycle["name"]) not in families]
if missing:
    raise SystemExit(f"Unclassified catalog cycles; output not changed: {missing}")
membership = {
    cycle["name"]: sorted(families[normalize(cycle["name"])])
    for cycle in catalog
}
# Canary Islands adapted itineraries are Grado C, absent from TodoFP Grados D.
adapted = json.loads((root / "scripts/src/data/fpa-adg.json").read_text())
for itinerary in adapted["itineraries"]:
    membership[itinerary["name"]] = [adapted["family"]]
target = root / "artifacts/api-server/src/lib/generated/fpCycleFamilies.ts"
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(
    "// Generated by scripts/generate-fp-family-catalog.py from official TodoFP indexes.\n"
    "// Cross-listed cycles intentionally belong to more than one family.\n"
    "// Includes Canary Islands FPA from scripts/src/data/fpa-adg.json (BOC 2025/046/918).\n"
    "export const fpCycleFamilies: Readonly<Record<string, readonly string[]>> = "
    + json.dumps(membership, ensure_ascii=False, indent=2) + ";\n"
)
print(f"Classified {len(membership)} existing cycles; wrote {target.relative_to(root)}")
